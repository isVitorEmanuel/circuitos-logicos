LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- DECODIFICADOR COMBINACIONAL: ESTADO DA FSM -> LUZES DAS DUAS VIAS.
-- CADA VIA TEM 3 BITS: (2) = VERMELHO, (1) = AMARELO, (0) = VERDE.
ENTITY DECODIFICADOR_LUZES IS
  PORT (
    ESTADO : IN  T_ESTADO;
    LUZ_A  : OUT STD_LOGIC_VECTOR(2 DOWNTO 0);
    LUZ_B  : OUT STD_LOGIC_VECTOR(2 DOWNTO 0)
  );
END ENTITY DECODIFICADOR_LUZES;

ARCHITECTURE RTL OF DECODIFICADOR_LUZES IS
  CONSTANT VERMELHO : STD_LOGIC_VECTOR(2 DOWNTO 0) := "100";
  CONSTANT AMARELO  : STD_LOGIC_VECTOR(2 DOWNTO 0) := "010";
  CONSTANT VERDE    : STD_LOGIC_VECTOR(2 DOWNTO 0) := "001";
BEGIN

  WITH ESTADO SELECT
    LUZ_A <= VERDE    WHEN VERDE_A,
             AMARELO  WHEN AMARELO_A,
             VERMELHO WHEN OTHERS;   -- OCIOSO, VERDE_B, AMARELO_B, FIM

  WITH ESTADO SELECT
    LUZ_B <= VERDE    WHEN VERDE_B,
             AMARELO  WHEN AMARELO_B,
             VERMELHO WHEN OTHERS;   -- OCIOSO, VERDE_A, AMARELO_A, FIM

END ARCHITECTURE RTL;

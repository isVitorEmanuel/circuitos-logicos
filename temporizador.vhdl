LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- CONTADOR REGRESSIVO PROGRAMAVEL.
ENTITY TEMPORIZADOR IS
  PORT (
    CLK      : IN  STD_LOGIC;
    RESET    : IN  STD_LOGIC;                            
    CARREGA  : IN  STD_LOGIC;                            
    HABILITA : IN  STD_LOGIC;                            
    DURACAO  : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    TC       : OUT STD_LOGIC
  );
END ENTITY TEMPORIZADOR;

ARCHITECTURE RTL OF TEMPORIZADOR IS
  SIGNAL CONT : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
BEGIN

  PROCESS (CLK)
  BEGIN
    IF RISING_EDGE(CLK) THEN
      IF RESET = '1' THEN
        CONT <= (OTHERS => '0');

      ELSIF CARREGA = '1' THEN
        IF DURACAO = 0 THEN
          CONT <= (OTHERS => '0');
        ELSE
          CONT <= DURACAO - 1;
        END IF;

      ELSIF HABILITA = '1' AND CONT /= 0 THEN
        CONT <= CONT - 1;
      END IF;
    END IF;
  END PROCESS;

  TC <= '1' WHEN CONT = 0 ELSE '0';

END ARCHITECTURE RTL;

LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- TESTE SIMPLES DO SISTEMA COMPLETO (TAMBEM EXERCITA A FSM):
--   1) UMA EXECUCAO COMPLETA, CONFERINDO AS LUZES CICLO A CICLO
--   2) START DURANTE A EXECUCAO E IGNORADO
--   3) DONE DURA 1 CICLO E O SISTEMA VOLTA A OCIOSO
--   4) RESET NO MEIO DA EXECUCAO VOLTA TUDO PARA VERMELHO
ENTITY TB_SEMAFORO_TOP IS
END ENTITY TB_SEMAFORO_TOP;

ARCHITECTURE SIM OF TB_SEMAFORO_TOP IS
  CONSTANT T_CLK : TIME := 10 NS;

  CONSTANT G_A   : POSITIVE := 4;
  CONSTANT Y_A   : POSITIVE := 2;
  CONSTANT G_B   : POSITIVE := 3;
  CONSTANT Y_B   : POSITIVE := 2;
  CONSTANT N_RND : POSITIVE := 2;
  CONSTANT SOMA  : POSITIVE := G_A + Y_A + G_B + Y_B;
  CONSTANT TOTAL : POSITIVE := N_RND * SOMA;

  CONSTANT VERMELHO : STD_LOGIC_VECTOR(2 DOWNTO 0) := "100";
  CONSTANT AMARELO  : STD_LOGIC_VECTOR(2 DOWNTO 0) := "010";
  CONSTANT VERDE    : STD_LOGIC_VECTOR(2 DOWNTO 0) := "001";

  SIGNAL CLK   : STD_LOGIC := '0';
  SIGNAL RESET : STD_LOGIC := '1';
  SIGNAL START : STD_LOGIC := '0';
  SIGNAL LUZ_A : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL LUZ_B : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL BUSY  : STD_LOGIC;
  SIGNAL DONE  : STD_LOGIC;
BEGIN

  CLK <= NOT CLK AFTER T_CLK / 2;

  DUT : ENTITY WORK.SEMAFORO_TOP
    GENERIC MAP (
      DUR_VERDE_A => G_A, DUR_AMARELO_A => Y_A,
      DUR_VERDE_B => G_B, DUR_AMARELO_B => Y_B,
      N_ROUNDS    => N_RND)
    PORT MAP (CLK => CLK, RESET => RESET, START => START,
              LUZ_A => LUZ_A, LUZ_B => LUZ_B, BUSY => BUSY, DONE => DONE);

  ESTIMULO : PROCESS
    VARIABLE ERROS  : NATURAL := 0;
    VARIABLE TESTES : NATURAL := 0;

    PROCEDURE ESPERADO (K : NATURAL; VARIABLE A, B : OUT STD_LOGIC_VECTOR(2 DOWNTO 0)) IS
      VARIABLE FASE : NATURAL := K MOD SOMA;
    BEGIN
      A := VERMELHO;
      B := VERMELHO;
      IF FASE < G_A THEN
        A := VERDE;
      ELSIF FASE < G_A + Y_A THEN
        A := AMARELO;
      ELSIF FASE < G_A + Y_A + G_B THEN
        B := VERDE;
      ELSE
        B := AMARELO;
      END IF;
    END PROCEDURE;

    PROCEDURE CHECA (COND : BOOLEAN; NOME : STRING) IS
    BEGIN
      TESTES := TESTES + 1;
      IF COND THEN
        REPORT "OK   " & NOME;
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO " & NOME SEVERITY ERROR;
      END IF;
    END PROCEDURE;

    PROCEDURE PROXIMO_CICLO IS
    BEGIN
      WAIT UNTIL RISING_EDGE(CLK);
      WAIT FOR 1 NS;
    END PROCEDURE;

    VARIABLE EA, EB    : STD_LOGIC_VECTOR(2 DOWNTO 0);
    VARIABLE CICLOS_OK : BOOLEAN := TRUE;
    VARIABLE SEGURO    : BOOLEAN := TRUE;
  BEGIN
    -- RESET INICIAL: TUDO VERMELHO, SEM BUSY, SEM DONE
    WAIT FOR 2 * T_CLK;
    RESET <= '0';
    PROXIMO_CICLO;
    CHECA(LUZ_A = VERMELHO AND LUZ_B = VERMELHO AND BUSY = '0' AND DONE = '0',
          "APOS RESET: OCIOSO, TUDO VERMELHO");

    -- 1) EXECUCAO COMPLETA COM PULSO DE START DE 1 CICLO
    START <= '1';
    WAIT UNTIL RISING_EDGE(CLK);   -- ESTE CLOCK AMOSTRA START
    START <= '0';
    WAIT FOR 1 NS;

    FOR K IN 0 TO TOTAL - 1 LOOP
      ESPERADO(K, EA, EB);
      IF LUZ_A /= EA OR LUZ_B /= EB OR BUSY /= '1' OR DONE /= '0' THEN
        CICLOS_OK := FALSE;
        REPORT "  DIVERGENCIA NO CICLO " & INTEGER'IMAGE(K) SEVERITY WARNING;
      END IF;
      IF LUZ_A = VERDE AND LUZ_B = VERDE THEN
        SEGURO := FALSE;
      END IF;

      -- 2) START NO MEIO DA EXECUCAO DEVE SER IGNORADO
      IF K = 3 THEN START <= '1'; ELSE START <= '0'; END IF;

      PROXIMO_CICLO;
    END LOOP;

    CHECA(CICLOS_OK, "LUZES CORRETAS NOS " & INTEGER'IMAGE(TOTAL) & " CICLOS (2 ROUNDS)");
    CHECA(SEGURO,    "NUNCA VERDE NAS DUAS VIAS");
    CHECA(START = '0', "START NO MEIO DA EXECUCAO NAO ESTENDEU A EXECUCAO");

    -- 3) CICLO DO DONE: TUDO VERMELHO, BUSY = 0, DONE = 1; DEPOIS VOLTA A OCIOSO
    CHECA(DONE = '1' AND BUSY = '0' AND LUZ_A = VERMELHO AND LUZ_B = VERMELHO,
          "DONE = 1 LOGO APOS " & INTEGER'IMAGE(TOTAL) & " CICLOS");
    PROXIMO_CICLO;
    CHECA(DONE = '0' AND BUSY = '0', "DONE DUROU 1 CICLO E VOLTOU A OCIOSO");

    -- 4) RESET NO MEIO DE UMA NOVA EXECUCAO
    START <= '1';
    WAIT UNTIL RISING_EDGE(CLK);
    START <= '0';
    WAIT FOR 1 NS;
    FOR K IN 1 TO 5 LOOP
      PROXIMO_CICLO;
    END LOOP;
    CHECA(BUSY = '1', "NOVA EXECUCAO COMECOU APOS O DONE");
    RESET <= '1';
    PROXIMO_CICLO;
    RESET <= '0';
    CHECA(LUZ_A = VERMELHO AND LUZ_B = VERMELHO AND BUSY = '0' AND DONE = '0',
          "RESET NO MEIO: VOLTOU A OCIOSO, TUDO VERMELHO");
    FOR K IN 1 TO 5 LOOP
      PROXIMO_CICLO;
    END LOOP;
    CHECA(BUSY = '0', "CONTINUA OCIOSO SEM NOVO START");

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM";
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " ERRO(S)" SEVERITY FAILURE;
    END IF;
    STD.ENV.FINISH;
  END PROCESS;

END ARCHITECTURE SIM;

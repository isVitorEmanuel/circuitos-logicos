LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- TESTE DO REGISTRADOR DE CONFIGURACAO COM BYPASS:
--   CAPTURA = '1': SAIDA ACOMPANHA A ENTRADA (BYPASS)
--   CAPTURA = '0': SAIDA FICA TRAVADA NO ULTIMO VALOR CAPTURADO
--   RESET ZERA O REGISTRADOR
ENTITY TB_REGISTRADOR_CONFIG IS
END ENTITY TB_REGISTRADOR_CONFIG;

ARCHITECTURE SIM OF TB_REGISTRADOR_CONFIG IS
  CONSTANT T_CLK : TIME := 10 NS;

  FUNCTION CFG (A, B, C, D, N : NATURAL) RETURN T_CONFIG IS
  BEGIN
    RETURN (DUR_VERDE_A   => TO_UNSIGNED(A, LARGURA_DUR),
            DUR_AMARELO_A => TO_UNSIGNED(B, LARGURA_DUR),
            DUR_VERDE_B   => TO_UNSIGNED(C, LARGURA_DUR),
            DUR_AMARELO_B => TO_UNSIGNED(D, LARGURA_DUR),
            N_ROUNDS      => TO_UNSIGNED(N, LARGURA_DUR));
  END FUNCTION;

  SIGNAL CLK     : STD_LOGIC := '0';
  SIGNAL RESET   : STD_LOGIC := '1';
  SIGNAL CAPTURA : STD_LOGIC := '1';
  SIGNAL ENTRADA : T_CONFIG  := CFG(1, 2, 3, 4, 5);
  SIGNAL SAIDA   : T_CONFIG;
BEGIN

  CLK <= NOT CLK AFTER T_CLK / 2;

  DUT : ENTITY WORK.REGISTRADOR_CONFIG
    PORT MAP (CLK => CLK, RESET => RESET, CAPTURA => CAPTURA,
              ENTRADA => ENTRADA, SAIDA => SAIDA);

  PROCESS
    VARIABLE ERROS  : NATURAL := 0;
    VARIABLE TESTES : NATURAL := 0;

    PROCEDURE CHECA (COND : BOOLEAN; NOME : STRING) IS
    BEGIN
      TESTES := TESTES + 1;
      IF COND THEN
        REPORT "OK   " & NOME;
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO " & NOME SEVERITY ERROR;
      END IF;
    END PROCEDURE;

    PROCEDURE PROXIMO_CICLO IS
    BEGIN
      WAIT UNTIL RISING_EDGE(CLK);
      WAIT FOR 1 NS;
    END PROCEDURE;
  BEGIN
    -- RESET: REGISTRADOR ZERADO (CAPTURA = '0' PARA VER O REGISTRADOR, NAO O BYPASS)
    CAPTURA <= '0';
    PROXIMO_CICLO;
    PROXIMO_CICLO;
    RESET <= '0';
    CHECA(SAIDA = CONFIG_ZERO, "APOS RESET: REGISTRADOR ZERADO");

    -- BYPASS: COM CAPTURA = '1' A SAIDA ENXERGA A ENTRADA ANTES DO CLOCK
    CAPTURA <= '1';
    WAIT FOR 1 NS;
    CHECA(SAIDA = CFG(1, 2, 3, 4, 5), "BYPASS: SAIDA = ENTRADA SEM ESPERAR O CLOCK");

    -- CAPTURA NO CLOCK
    PROXIMO_CICLO;
    CAPTURA <= '0';
    WAIT FOR 1 NS;
    CHECA(SAIDA = CFG(1, 2, 3, 4, 5), "VALOR CAPTURADO NO CLOCK");

    -- TRAVA: MUDAR A ENTRADA COM CAPTURA = '0' NAO ALTERA A SAIDA
    ENTRADA <= CFG(9, 8, 7, 6, 3);
    PROXIMO_CICLO;
    PROXIMO_CICLO;
    CHECA(SAIDA = CFG(1, 2, 3, 4, 5), "TRAVADO: ENTRADA MUDOU, SAIDA NAO");

    -- NOVA CAPTURA
    CAPTURA <= '1';
    PROXIMO_CICLO;
    CAPTURA <= '0';
    ENTRADA <= CFG(0, 0, 0, 0, 0);
    WAIT FOR 1 NS;
    CHECA(SAIDA = CFG(9, 8, 7, 6, 3), "NOVA CAPTURA: GUARDOU O VALOR NOVO");

    -- RESET NO MEIO
    RESET <= '1';
    PROXIMO_CICLO;
    RESET <= '0';
    CHECA(SAIDA = CONFIG_ZERO, "RESET ZEROU O REGISTRADOR");

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM";
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " ERRO(S)" SEVERITY FAILURE;
    END IF;
    STD.ENV.FINISH;
  END PROCESS;

END ARCHITECTURE SIM;

LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- TESTE SIMPLES: CADA ESTADO DEVOLVE A DURACAO CONFIGURADA NOS GENERICS.
ENTITY TB_TABELA_DURACAO IS
END ENTITY TB_TABELA_DURACAO;

ARCHITECTURE SIM OF TB_TABELA_DURACAO IS
  SIGNAL ESTADO  : T_ESTADO := OCIOSO;
  SIGNAL DURACAO : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
BEGIN

  -- VALORES DIFERENTES ENTRE SI PARA NAO CONFUNDIR UM ESTADO COM OUTRO
  DUT : ENTITY WORK.TABELA_DURACAO
    GENERIC MAP (DUR_VERDE_A => 5, DUR_AMARELO_A => 2,
                 DUR_VERDE_B => 7, DUR_AMARELO_B => 255)
    PORT MAP (ESTADO => ESTADO, DURACAO => DURACAO);

  PROCESS
    VARIABLE ERROS : NATURAL := 0;
    VARIABLE TESTES : NATURAL := 0;

    PROCEDURE CHECA (E : T_ESTADO; ESPERADO : NATURAL) IS
    BEGIN
      ESTADO <= E;
      WAIT FOR 1 NS;
      TESTES := TESTES + 1;
      IF TO_INTEGER(DURACAO) = ESPERADO THEN
        REPORT "OK   " & T_ESTADO'IMAGE(E) & " = " & INTEGER'IMAGE(ESPERADO);
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO " & T_ESTADO'IMAGE(E) & ": ESPERADO " & INTEGER'IMAGE(ESPERADO) &
               ", OBTIDO " & INTEGER'IMAGE(TO_INTEGER(DURACAO)) SEVERITY ERROR;
      END IF;
    END PROCEDURE;
  BEGIN
    CHECA(VERDE_A,   5);
    CHECA(AMARELO_A, 2);
    CHECA(VERDE_B,   7);
    CHECA(AMARELO_B, 255);
    CHECA(OCIOSO,    1);
    CHECA(FIM,       1);

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM";
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " ERRO(S)" SEVERITY FAILURE;
    END IF;
    STD.ENV.FINISH;
  END PROCESS;

END ARCHITECTURE SIM;

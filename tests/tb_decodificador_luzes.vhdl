LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

ENTITY TB_DECODIFICADOR_LUZES IS
END ENTITY TB_DECODIFICADOR_LUZES;

ARCHITECTURE SIM OF TB_DECODIFICADOR_LUZES IS
  CONSTANT VERMELHO : STD_LOGIC_VECTOR(2 DOWNTO 0) := "100";
  CONSTANT AMARELO  : STD_LOGIC_VECTOR(2 DOWNTO 0) := "010";
  CONSTANT VERDE    : STD_LOGIC_VECTOR(2 DOWNTO 0) := "001";

  SIGNAL ESTADO : T_ESTADO := OCIOSO;
  SIGNAL LUZ_A  : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL LUZ_B  : STD_LOGIC_VECTOR(2 DOWNTO 0);
BEGIN

  DUT : ENTITY WORK.DECODIFICADOR_LUZES
    PORT MAP (ESTADO => ESTADO, LUZ_A => LUZ_A, LUZ_B => LUZ_B);

  PROCESS
    VARIABLE ERROS : NATURAL := 0;
    VARIABLE TESTES : NATURAL := 0;

    PROCEDURE CHECA (E : T_ESTADO; A, B : STD_LOGIC_VECTOR(2 DOWNTO 0)) IS
    BEGIN
      ESTADO <= E;
      WAIT FOR 1 NS;
      TESTES := TESTES + 1;
      IF LUZ_A = A AND LUZ_B = B THEN
        REPORT "OK   " & T_ESTADO'IMAGE(E);
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO " & T_ESTADO'IMAGE(E) & ": LUZES INCORRETAS" SEVERITY ERROR;
      END IF;
      -- SEGURANCA: NUNCA VERDE NAS DUAS VIAS
      IF LUZ_A = VERDE AND LUZ_B = VERDE THEN
        ERROS := ERROS + 1;
        REPORT "ERRO: VERDE NAS DUAS VIAS" SEVERITY ERROR;
      END IF;
    END PROCEDURE;
  BEGIN
    CHECA(OCIOSO,    VERMELHO, VERMELHO);
    CHECA(VERDE_A,   VERDE,    VERMELHO);
    CHECA(AMARELO_A, AMARELO,  VERMELHO);
    CHECA(VERDE_B,   VERMELHO, VERDE);
    CHECA(AMARELO_B, VERMELHO, AMARELO);
    CHECA(FIM,       VERMELHO, VERMELHO);

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM";
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " ERRO(S)" SEVERITY FAILURE;
    END IF;
    STD.ENV.FINISH;
  END PROCESS;

END ARCHITECTURE SIM;

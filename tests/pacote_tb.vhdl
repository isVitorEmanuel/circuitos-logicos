LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- PACOTE DE APOIO DOS TESTBENCHES POR CASO (tests/casos/tb_caso_NN.vhdl).
-- EXECUTA_CASO FAZ O ROTEIRO COMPLETO DO ENUNCIADO PARA UM CONJUNTO DE DADOS:
--   RESET -> APLICA DADOS -> START -> AGUARDA DONE -> VERIFICA O RESULTADO.
-- RESULTADO CORRETO CONHECIDO: CICLOS = N * (G_A + Y_A + G_B + Y_B), COM 0 TRATADO COMO 1.
PACKAGE PACOTE_TB IS

  -- UM CONJUNTO DE DADOS DE ENTRADA
  TYPE T_CASO IS RECORD
    G_A, Y_A, G_B, Y_B, N : NATURAL;
  END RECORD T_CASO;

  PROCEDURE EXECUTA_CASO (
    CONSTANT NUM   : IN  NATURAL;
    CONSTANT C     : IN  T_CASO;
    SIGNAL CLK     : IN  STD_LOGIC;
    SIGNAL RESET   : OUT STD_LOGIC;
    SIGNAL START   : OUT STD_LOGIC;
    SIGNAL DUR_VERDE_A, DUR_AMARELO_A, DUR_VERDE_B, DUR_AMARELO_B, N_ROUNDS
                   : OUT UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    SIGNAL LUZ_A, LUZ_B : IN STD_LOGIC_VECTOR(2 DOWNTO 0);
    SIGNAL BUSY, DONE   : IN STD_LOGIC;
    SIGNAL CASO_ATUAL   : OUT NATURAL
  );

END PACKAGE PACOTE_TB;

PACKAGE BODY PACOTE_TB IS

  CONSTANT VERMELHO : STD_LOGIC_VECTOR(2 DOWNTO 0) := "100";
  CONSTANT AMARELO  : STD_LOGIC_VECTOR(2 DOWNTO 0) := "010";
  CONSTANT VERDE    : STD_LOGIC_VECTOR(2 DOWNTO 0) := "001";

  -- 0 E TRATADO COMO 1 (IGUAL AO HARDWARE)
  FUNCTION EFET (X : NATURAL) RETURN POSITIVE IS
  BEGIN
    IF X = 0 THEN RETURN 1; ELSE RETURN X; END IF;
  END FUNCTION;

  PROCEDURE EXECUTA_CASO (
    CONSTANT NUM   : IN  NATURAL;
    CONSTANT C     : IN  T_CASO;
    SIGNAL CLK     : IN  STD_LOGIC;
    SIGNAL RESET   : OUT STD_LOGIC;
    SIGNAL START   : OUT STD_LOGIC;
    SIGNAL DUR_VERDE_A, DUR_AMARELO_A, DUR_VERDE_B, DUR_AMARELO_B, N_ROUNDS
                   : OUT UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    SIGNAL LUZ_A, LUZ_B : IN STD_LOGIC_VECTOR(2 DOWNTO 0);
    SIGNAL BUSY, DONE   : IN STD_LOGIC;
    SIGNAL CASO_ATUAL   : OUT NATURAL
  ) IS
    VARIABLE ERROS      : NATURAL := 0;
    VARIABLE TESTES     : NATURAL := 0;
    VARIABLE ESP_CICLOS : NATURAL;
    VARIABLE OBT_CICLOS : NATURAL := 0;
    VARIABLE EA, EB     : STD_LOGIC_VECTOR(2 DOWNTO 0);
    VARIABLE LUZES_OK   : BOOLEAN := TRUE;
    VARIABLE SEGURO     : BOOLEAN := TRUE;
    VARIABLE BUSY_OK    : BOOLEAN := TRUE;
    CONSTANT ROTULO     : STRING := "CASO " & INTEGER'IMAGE(NUM) & ": ";

    PROCEDURE CHECA (COND : BOOLEAN; NOME : STRING) IS
    BEGIN
      TESTES := TESTES + 1;
      IF COND THEN
        REPORT "OK   " & NOME;
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO " & NOME SEVERITY ERROR;
      END IF;
    END PROCEDURE;

    PROCEDURE PROXIMO_CICLO IS
    BEGIN
      WAIT UNTIL RISING_EDGE(CLK);
      WAIT FOR 1 NS;
    END PROCEDURE;

    -- LUZES ESPERADAS NO CICLO K (CONTADO A PARTIR DO CLOCK DO START)
    PROCEDURE ESPERADO (K : NATURAL; VARIABLE A, B : OUT STD_LOGIC_VECTOR(2 DOWNTO 0)) IS
      VARIABLE SOMA : NATURAL := EFET(C.G_A) + EFET(C.Y_A) + EFET(C.G_B) + EFET(C.Y_B);
      VARIABLE FASE : NATURAL := K MOD SOMA;
    BEGIN
      A := VERMELHO;
      B := VERMELHO;
      IF FASE < EFET(C.G_A) THEN
        A := VERDE;
      ELSIF FASE < EFET(C.G_A) + EFET(C.Y_A) THEN
        A := AMARELO;
      ELSIF FASE < EFET(C.G_A) + EFET(C.Y_A) + EFET(C.G_B) THEN
        B := VERDE;
      ELSE
        B := AMARELO;
      END IF;
    END PROCEDURE;
  BEGIN
    CASO_ATUAL <= NUM;
    ESP_CICLOS := EFET(C.N) * (EFET(C.G_A) + EFET(C.Y_A) + EFET(C.G_B) + EFET(C.Y_B));

    -- 1) RESET
    RESET <= '1';
    PROXIMO_CICLO;
    PROXIMO_CICLO;
    RESET <= '0';
    PROXIMO_CICLO;

    -- 2) APLICA OS DADOS DE ENTRADA
    DUR_VERDE_A   <= TO_UNSIGNED(C.G_A, LARGURA_DUR);
    DUR_AMARELO_A <= TO_UNSIGNED(C.Y_A, LARGURA_DUR);
    DUR_VERDE_B   <= TO_UNSIGNED(C.G_B, LARGURA_DUR);
    DUR_AMARELO_B <= TO_UNSIGNED(C.Y_B, LARGURA_DUR);
    N_ROUNDS      <= TO_UNSIGNED(C.N,   LARGURA_DUR);
    PROXIMO_CICLO;

    -- 3) START (PULSO DE 1 CICLO)
    START <= '1';
    WAIT UNTIL RISING_EDGE(CLK);   -- ESTE CLOCK AMOSTRA START
    START <= '0';
    WAIT FOR 1 NS;

    -- 4) AGUARDA DONE, CONTANDO OS CICLOS E CONFERINDO AS LUZES
    WHILE DONE = '0' AND OBT_CICLOS <= ESP_CICLOS LOOP
      ESPERADO(OBT_CICLOS, EA, EB);
      IF LUZ_A /= EA OR LUZ_B /= EB THEN
        LUZES_OK := FALSE;
      END IF;
      IF LUZ_A = VERDE AND LUZ_B = VERDE THEN
        SEGURO := FALSE;
      END IF;
      IF BUSY /= '1' THEN
        BUSY_OK := FALSE;
      END IF;
      OBT_CICLOS := OBT_CICLOS + 1;
      PROXIMO_CICLO;
    END LOOP;

    -- 5) VERIFICA O RESULTADO
    REPORT "TABELA;" & INTEGER'IMAGE(NUM) & ";" & INTEGER'IMAGE(C.G_A) & ";" &
           INTEGER'IMAGE(C.Y_A) & ";" & INTEGER'IMAGE(C.G_B) & ";" &
           INTEGER'IMAGE(C.Y_B) & ";" & INTEGER'IMAGE(C.N) & ";" &
           INTEGER'IMAGE(ESP_CICLOS) & ";" & INTEGER'IMAGE(OBT_CICLOS) & ";" &
           BOOLEAN'IMAGE(OBT_CICLOS = ESP_CICLOS AND LUZES_OK AND SEGURO);

    CHECA(OBT_CICLOS = ESP_CICLOS,
          ROTULO & "CICLOS ESPERADO " & INTEGER'IMAGE(ESP_CICLOS) &
          ", OBTIDO " & INTEGER'IMAGE(OBT_CICLOS));
    CHECA(LUZES_OK AND SEGURO AND BUSY_OK,
          ROTULO & "LUZES CORRETAS EM TODOS OS CICLOS, NUNCA VERDE NAS DUAS VIAS, BUSY = 1");
    CHECA(DONE = '1' AND BUSY = '0' AND LUZ_A = VERMELHO AND LUZ_B = VERMELHO,
          ROTULO & "DONE = 1, BUSY = 0, TUDO VERMELHO");
    PROXIMO_CICLO;
    CHECA(DONE = '0' AND BUSY = '0',
          ROTULO & "DONE DUROU 1 CICLO, VOLTOU A OCIOSO");

    PROXIMO_CICLO;   -- FOLGA FINAL PARA A ONDA

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM";
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " ERRO(S)" SEVERITY FAILURE;
    END IF;
    STD.ENV.FINISH;
  END PROCEDURE EXECUTA_CASO;

END PACKAGE BODY PACOTE_TB;

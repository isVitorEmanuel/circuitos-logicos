LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- TESTBENCH COMPLETO (ENUNCIADO, ITENS 4 E 5): 10 CONJUNTOS DE DADOS.
-- CADA CASO = (DUR_VERDE_A, DUR_AMARELO_A, DUR_VERDE_B, DUR_AMARELO_B, N_ROUNDS).
-- RESULTADO CORRETO CONHECIDO: CICLOS = N * (G_A + Y_A + G_B + Y_B), COM 0 TRATADO COMO 1.
-- PARA CADA CASO O TESTBENCH:
--   1) APLICA OS DADOS E GERA UM PULSO DE START DE 1 CICLO
--   2) CONTA OS CICLOS ATE O DONE E COMPARA COM O ESPERADO
--   3) CONFERE AS LUZES CICLO A CICLO (E QUE NUNCA HA VERDE NAS DUAS VIAS)
--   4) CONFERE QUE DONE DURA 1 CICLO E O SISTEMA VOLTA A OCIOSO
-- AS LINHAS "TABELA;..." DO LOG FORMAM A TABELA ENTRADA / ESPERADO / OBTIDO / CICLOS.
ENTITY TB_CASOS_SEMAFORO IS
END ENTITY TB_CASOS_SEMAFORO;

ARCHITECTURE SIM OF TB_CASOS_SEMAFORO IS
  CONSTANT T_CLK : TIME := 10 NS;

  TYPE T_CASO IS RECORD
    G_A, Y_A, G_B, Y_B, N : NATURAL;
  END RECORD;
  TYPE T_CASOS IS ARRAY (NATURAL RANGE <>) OF T_CASO;

  CONSTANT CASOS : T_CASOS(1 TO 10) := (
    (10,   3, 10,   3,   2),   --  1) VALORES PADRAO DO PROJETO
    ( 4,   2,  3,   2,   2),   --  2) CASO DO TESTE SIMPLES
    ( 1,   1,  1,   1,   1),   --  3) MINIMO: 1 CICLO POR ESTADO, 1 ROUND
    ( 1,   1,  1,   1,   5),   --  4) MINIMO COM VARIOS ROUNDS
    ( 5,   2,  7,   3,   1),   --  5) VIAS ASSIMETRICAS, 1 ROUND
    (255,  1,  1, 255,   1),   --  6) DURACOES MAXIMAS (255)
    ( 0,   0,  0,   0,   0),   --  7) TUDO ZERO (REGRA 0 = 1)
    ( 3,   1,  8,   2,   4),   --  8) ASSIMETRICO, 4 ROUNDS
    ( 7,   7,  7,   7,   3),   --  9) TODAS IGUAIS
    ( 1,   1,  1,   1, 255));  -- 10) ROUNDS MAXIMOS (255)

  CONSTANT VERMELHO : STD_LOGIC_VECTOR(2 DOWNTO 0) := "100";
  CONSTANT AMARELO  : STD_LOGIC_VECTOR(2 DOWNTO 0) := "010";
  CONSTANT VERDE    : STD_LOGIC_VECTOR(2 DOWNTO 0) := "001";

  SIGNAL CLK   : STD_LOGIC := '0';
  SIGNAL RESET : STD_LOGIC := '1';
  SIGNAL START : STD_LOGIC := '0';
  SIGNAL DUR_VERDE_A   : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL DUR_AMARELO_A : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL DUR_VERDE_B   : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL DUR_AMARELO_B : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL N_ROUNDS      : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL LUZ_A : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL LUZ_B : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL BUSY  : STD_LOGIC;
  SIGNAL DONE  : STD_LOGIC;

  SIGNAL CASO_ATUAL : NATURAL := 0;   -- SO PARA APARECER NAS FORMAS DE ONDA

  -- 0 E TRATADO COMO 1 (IGUAL AO HARDWARE)
  FUNCTION EFET (X : NATURAL) RETURN POSITIVE IS
  BEGIN
    IF X = 0 THEN RETURN 1; ELSE RETURN X; END IF;
  END FUNCTION;
BEGIN

  CLK <= NOT CLK AFTER T_CLK / 2;

  DUT : ENTITY WORK.SEMAFORO_TOP
    PORT MAP (CLK => CLK, RESET => RESET, START => START,
              DUR_VERDE_A => DUR_VERDE_A, DUR_AMARELO_A => DUR_AMARELO_A,
              DUR_VERDE_B => DUR_VERDE_B, DUR_AMARELO_B => DUR_AMARELO_B,
              N_ROUNDS => N_ROUNDS,
              LUZ_A => LUZ_A, LUZ_B => LUZ_B, BUSY => BUSY, DONE => DONE);

  ESTIMULO : PROCESS
    VARIABLE ERROS  : NATURAL := 0;
    VARIABLE TESTES : NATURAL := 0;

    PROCEDURE CHECA (COND : BOOLEAN; NOME : STRING) IS
    BEGIN
      TESTES := TESTES + 1;
      IF COND THEN
        REPORT "OK   " & NOME;
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO " & NOME SEVERITY ERROR;
      END IF;
    END PROCEDURE;

    PROCEDURE PROXIMO_CICLO IS
    BEGIN
      WAIT UNTIL RISING_EDGE(CLK);
      WAIT FOR 1 NS;
    END PROCEDURE;

    -- LUZES ESPERADAS NO CICLO K (CONTADO A PARTIR DO CLOCK DO START)
    PROCEDURE ESPERADO (C : T_CASO; K : NATURAL;
                        VARIABLE A, B : OUT STD_LOGIC_VECTOR(2 DOWNTO 0)) IS
      VARIABLE SOMA : NATURAL := EFET(C.G_A) + EFET(C.Y_A) + EFET(C.G_B) + EFET(C.Y_B);
      VARIABLE FASE : NATURAL := K MOD SOMA;
    BEGIN
      A := VERMELHO;
      B := VERMELHO;
      IF FASE < EFET(C.G_A) THEN
        A := VERDE;
      ELSIF FASE < EFET(C.G_A) + EFET(C.Y_A) THEN
        A := AMARELO;
      ELSIF FASE < EFET(C.G_A) + EFET(C.Y_A) + EFET(C.G_B) THEN
        B := VERDE;
      ELSE
        B := AMARELO;
      END IF;
    END PROCEDURE;

    VARIABLE C          : T_CASO;
    VARIABLE ESP_CICLOS : NATURAL;
    VARIABLE OBT_CICLOS : NATURAL;
    VARIABLE EA, EB     : STD_LOGIC_VECTOR(2 DOWNTO 0);
    VARIABLE LUZES_OK   : BOOLEAN;
    VARIABLE SEGURO     : BOOLEAN;
    VARIABLE BUSY_OK    : BOOLEAN;
  BEGIN
    -- RESET INICIAL
    WAIT FOR 2 * T_CLK;
    RESET <= '0';
    PROXIMO_CICLO;

    REPORT "TABELA;CASO;G_A;Y_A;G_B;Y_B;N;ESPERADO;OBTIDO;RESULTADO";

    FOR I IN CASOS'RANGE LOOP
      C := CASOS(I);
      CASO_ATUAL <= I;
      ESP_CICLOS := EFET(C.N) * (EFET(C.G_A) + EFET(C.Y_A) + EFET(C.G_B) + EFET(C.Y_B));

      -- 1) APLICA OS DADOS E, UM CICLO DEPOIS, UM PULSO DE START
      DUR_VERDE_A   <= TO_UNSIGNED(C.G_A, LARGURA_DUR);
      DUR_AMARELO_A <= TO_UNSIGNED(C.Y_A, LARGURA_DUR);
      DUR_VERDE_B   <= TO_UNSIGNED(C.G_B, LARGURA_DUR);
      DUR_AMARELO_B <= TO_UNSIGNED(C.Y_B, LARGURA_DUR);
      N_ROUNDS      <= TO_UNSIGNED(C.N,   LARGURA_DUR);
      PROXIMO_CICLO;

      START <= '1';
      WAIT UNTIL RISING_EDGE(CLK);   -- ESTE CLOCK AMOSTRA START
      START <= '0';
      WAIT FOR 1 NS;

      -- 2) E 3) CONTA OS CICLOS ATE O DONE, CONFERINDO AS LUZES
      OBT_CICLOS := 0;
      LUZES_OK   := TRUE;
      SEGURO     := TRUE;
      BUSY_OK    := TRUE;
      WHILE DONE = '0' AND OBT_CICLOS <= ESP_CICLOS LOOP
        ESPERADO(C, OBT_CICLOS, EA, EB);
        IF LUZ_A /= EA OR LUZ_B /= EB THEN
          LUZES_OK := FALSE;
        END IF;
        IF LUZ_A = VERDE AND LUZ_B = VERDE THEN
          SEGURO := FALSE;
        END IF;
        IF BUSY /= '1' THEN
          BUSY_OK := FALSE;
        END IF;
        OBT_CICLOS := OBT_CICLOS + 1;
        PROXIMO_CICLO;
      END LOOP;

      REPORT "TABELA;" & INTEGER'IMAGE(I) & ";" & INTEGER'IMAGE(C.G_A) & ";" &
             INTEGER'IMAGE(C.Y_A) & ";" & INTEGER'IMAGE(C.G_B) & ";" &
             INTEGER'IMAGE(C.Y_B) & ";" & INTEGER'IMAGE(C.N) & ";" &
             INTEGER'IMAGE(ESP_CICLOS) & ";" & INTEGER'IMAGE(OBT_CICLOS) & ";" &
             BOOLEAN'IMAGE(OBT_CICLOS = ESP_CICLOS AND LUZES_OK AND SEGURO);

      CHECA(OBT_CICLOS = ESP_CICLOS,
            "CASO " & INTEGER'IMAGE(I) & ": CICLOS ESPERADO " & INTEGER'IMAGE(ESP_CICLOS) &
            ", OBTIDO " & INTEGER'IMAGE(OBT_CICLOS));
      CHECA(LUZES_OK AND SEGURO AND BUSY_OK,
            "CASO " & INTEGER'IMAGE(I) & ": LUZES CORRETAS EM TODOS OS CICLOS, NUNCA VERDE NAS DUAS VIAS, BUSY = 1");

      -- 4) DONE DURA 1 CICLO E O SISTEMA VOLTA A OCIOSO
      CHECA(DONE = '1' AND BUSY = '0' AND LUZ_A = VERMELHO AND LUZ_B = VERMELHO,
            "CASO " & INTEGER'IMAGE(I) & ": DONE = 1, BUSY = 0, TUDO VERMELHO");
      PROXIMO_CICLO;
      CHECA(DONE = '0' AND BUSY = '0',
            "CASO " & INTEGER'IMAGE(I) & ": DONE DUROU 1 CICLO, VOLTOU A OCIOSO");

      PROXIMO_CICLO;   -- FOLGA ENTRE CASOS
    END LOOP;

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM";
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " ERRO(S)" SEVERITY FAILURE;
    END IF;
    STD.ENV.FINISH;
  END PROCESS;

END ARCHITECTURE SIM;

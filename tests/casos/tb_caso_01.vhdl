LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;
USE WORK.PACOTE_TB.ALL;

-- CASO DE TESTE 1: VALORES PADRAO DO PROJETO
--   DUR_VERDE_A = 10, DUR_AMARELO_A = 3, DUR_VERDE_B = 10, DUR_AMARELO_B = 3, N_ROUNDS = 2
--   RESULTADO ESPERADO: 52 CICLOS (N * SOMA DAS DURACOES, COM 0 = 1)
ENTITY TB_CASO_01 IS
END ENTITY TB_CASO_01;

ARCHITECTURE SIM OF TB_CASO_01 IS
  CONSTANT CASO : T_CASO := (10, 3, 10, 3, 2);   -- G_A, Y_A, G_B, Y_B, N

  SIGNAL CLK   : STD_LOGIC := '0';
  SIGNAL RESET : STD_LOGIC := '1';
  SIGNAL START : STD_LOGIC := '0';
  SIGNAL DUR_VERDE_A   : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL DUR_AMARELO_A : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL DUR_VERDE_B   : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL DUR_AMARELO_B : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL N_ROUNDS      : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL LUZ_A : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL LUZ_B : STD_LOGIC_VECTOR(2 DOWNTO 0);
  SIGNAL BUSY  : STD_LOGIC;
  SIGNAL DONE  : STD_LOGIC;
  SIGNAL CASO_ATUAL : NATURAL := 0;   -- SO PARA APARECER NAS FORMAS DE ONDA
BEGIN

  CLK <= NOT CLK AFTER 5 NS;

  DUT : ENTITY WORK.SEMAFORO_TOP
    PORT MAP (CLK => CLK, RESET => RESET, START => START,
              DUR_VERDE_A => DUR_VERDE_A, DUR_AMARELO_A => DUR_AMARELO_A,
              DUR_VERDE_B => DUR_VERDE_B, DUR_AMARELO_B => DUR_AMARELO_B,
              N_ROUNDS => N_ROUNDS,
              LUZ_A => LUZ_A, LUZ_B => LUZ_B, BUSY => BUSY, DONE => DONE);

  ESTIMULO : PROCESS
  BEGIN
    EXECUTA_CASO(1, CASO, CLK, RESET, START,
                 DUR_VERDE_A, DUR_AMARELO_A, DUR_VERDE_B, DUR_AMARELO_B, N_ROUNDS,
                 LUZ_A, LUZ_B, BUSY, DONE, CASO_ATUAL);
    WAIT;
  END PROCESS;

END ARCHITECTURE SIM;

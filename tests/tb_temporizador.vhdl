LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

ENTITY TB_TEMPORIZADOR IS
END ENTITY TB_TEMPORIZADOR;

ARCHITECTURE SIM OF TB_TEMPORIZADOR IS
  CONSTANT T_CLK : TIME := 10 NS;

  SIGNAL CLK      : STD_LOGIC := '0';
  SIGNAL RESET    : STD_LOGIC := '1';
  SIGNAL CARREGA  : STD_LOGIC := '0';
  SIGNAL HABILITA : STD_LOGIC := '0';
  SIGNAL DURACAO  : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL TC       : STD_LOGIC;
BEGIN

  CLK <= NOT CLK AFTER T_CLK / 2;

  DUT : ENTITY WORK.TEMPORIZADOR
    PORT MAP (CLK => CLK, RESET => RESET, CARREGA => CARREGA,
              HABILITA => HABILITA, DURACAO => DURACAO, TC => TC);

  ESTIMULO : PROCESS
    VARIABLE ERROS  : NATURAL := 0;
    VARIABLE TESTES : NATURAL := 0;

    -- ESPERA N BORDAS DE SUBIDA DO CLOCK
    PROCEDURE ESPERA_CLK (N : NATURAL) IS
    BEGIN
      FOR I IN 1 TO N LOOP
        WAIT UNTIL RISING_EDGE(CLK);
      END LOOP;
    END PROCEDURE;

    -- CARREGA UMA DURACAO (CARREGA = '1' DURANTE UMA BORDA)
    PROCEDURE CARREGA_VALOR (D : NATURAL) IS
    BEGIN
      DURACAO <= TO_UNSIGNED(D, LARGURA_DUR);
      CARREGA <= '1';
      WAIT UNTIL RISING_EDGE(CLK);
      CARREGA <= '0';
    END PROCEDURE;

    -- CONTA CICLOS ATE TC = '1' E COMPARA COM O ESPERADO
    PROCEDURE CONTA_ATE_TC (ESPERADO : NATURAL; NOME : STRING) IS
      VARIABLE N : NATURAL := 0;
    BEGIN
      TESTES := TESTES + 1;
      LOOP
        WAIT UNTIL RISING_EDGE(CLK);
        N := N + 1;
        EXIT WHEN TC = '1' OR N > 1000;
      END LOOP;

      IF N = ESPERADO THEN
        REPORT "OK   [" & NOME & "]: " & INTEGER'IMAGE(N) & " CICLOS";
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO [" & NOME & "]: ESPERADO " & INTEGER'IMAGE(ESPERADO) &
               ", OBTIDO " & INTEGER'IMAGE(N) SEVERITY ERROR;
      END IF;
    END PROCEDURE;

    -- VERIFICA O VALOR DE TC LOGO APOS A ULTIMA BORDA
    PROCEDURE CHECA_TC (ESPERADO : STD_LOGIC; NOME : STRING) IS
    BEGIN
      TESTES := TESTES + 1;
      WAIT FOR 1 NS;
      IF TC = ESPERADO THEN
        REPORT "OK   [" & NOME & "]";
      ELSE
        ERROS := ERROS + 1;
        REPORT "ERRO [" & NOME & "]: TC INESPERADO" SEVERITY ERROR;
      END IF;
    END PROCEDURE;

  BEGIN
    -- RESET INICIAL
    WAIT FOR 2 * T_CLK;
    RESET <= '0';
    HABILITA <= '1';
    WAIT UNTIL RISING_EDGE(CLK);

    -- TESTE 1: DURACOES NORMAIS (D CICLOS EXATOS)
    CARREGA_VALOR(1);   CONTA_ATE_TC(1,   "D=1");
    CARREGA_VALOR(2);   CONTA_ATE_TC(2,   "D=2");
    CARREGA_VALOR(3);   CONTA_ATE_TC(3,   "D=3");
    CARREGA_VALOR(5);   CONTA_ATE_TC(5,   "D=5");
    CARREGA_VALOR(10);  CONTA_ATE_TC(10,  "D=10");
    CARREGA_VALOR(100); CONTA_ATE_TC(100, "D=100");
    CARREGA_VALOR(255); CONTA_ATE_TC(255, "D=255 (MAXIMO)");

    -- TESTE 2: PROTECAO DURACAO = 0 (TRATADA COMO 1)
    CARREGA_VALOR(0);   CONTA_ATE_TC(1,   "D=0 VIRA 1");

    -- TESTE 3: HABILITA = '0' CONGELA A CONTAGEM
    HABILITA <= '0';
    CARREGA_VALOR(5);
    ESPERA_CLK(6);
    CHECA_TC('0', "PAUSA: TC CONTINUA 0 SEM HABILITA");
    HABILITA <= '1';
    CONTA_ATE_TC(5, "RETOMA APOS PAUSA (5 CICLOS)");

    -- TESTE 4: RESET NO MEIO DA CONTAGEM ZERA O CONTADOR
    CARREGA_VALOR(10);
    ESPERA_CLK(3);
    RESET <= '1';
    WAIT UNTIL RISING_EDGE(CLK);
    RESET <= '0';
    CHECA_TC('1', "RESET NO MEIO: TC = 1");

    -- TESTE 5: RECARGA NO MEIO DA CONTAGEM
    CARREGA_VALOR(10);
    ESPERA_CLK(3);
    CARREGA_VALOR(4);
    CONTA_ATE_TC(4, "RECARGA NO MEIO: NOVA DURACAO 4");

    -- TESTE 6: TC PERMANECE EM 1 APOS TERMINAR (SEM CARREGA)
    CARREGA_VALOR(2);
    CONTA_ATE_TC(2, "D=2 ANTES DE CHECAR PERMANENCIA");
    ESPERA_CLK(3);
    CHECA_TC('1', "TC PERMANECE 1 ATE NOVA CARGA");

    IF ERROS = 0 THEN
      REPORT "TODOS OS " & INTEGER'IMAGE(TESTES) & " TESTES PASSARAM" SEVERITY NOTE;
    ELSE
      REPORT INTEGER'IMAGE(ERROS) & " DE " & INTEGER'IMAGE(TESTES) &
             " TESTES FALHARAM" SEVERITY ERROR;
    END IF;

    WAIT;
  END PROCESS;

END ARCHITECTURE SIM;

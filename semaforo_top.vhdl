LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- TOP-LEVEL: INTERFACE CLK / RESET / START / DONE + LUZES DAS DUAS VIAS.
-- DADOS DE ENTRADA: DURACAO DE CADA ESTADO E NUMERO DE ROUNDS (PORTAS).
-- ELES SAO LIDOS NO CLOCK EM QUE O START E AMOSTRADO E FICAM TRAVADOS ATE O DONE.
ENTITY SEMAFORO_TOP IS
  PORT (
    CLK           : IN  STD_LOGIC;
    RESET         : IN  STD_LOGIC;
    START         : IN  STD_LOGIC;
    DUR_VERDE_A   : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    DUR_AMARELO_A : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    DUR_VERDE_B   : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    DUR_AMARELO_B : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    N_ROUNDS      : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    LUZ_A : OUT STD_LOGIC_VECTOR(2 DOWNTO 0);   -- (2)=VERMELHO (1)=AMARELO (0)=VERDE
    LUZ_B : OUT STD_LOGIC_VECTOR(2 DOWNTO 0);
    BUSY  : OUT STD_LOGIC;
    DONE  : OUT STD_LOGIC
  );
END ENTITY SEMAFORO_TOP;

ARCHITECTURE RTL OF SEMAFORO_TOP IS
  SIGNAL S_ESTADO      : T_ESTADO;
  SIGNAL S_ESTADO_PROX : T_ESTADO;
  SIGNAL S_CARREGA     : STD_LOGIC;
  SIGNAL S_TC          : STD_LOGIC;
  SIGNAL S_BUSY        : STD_LOGIC;
  SIGNAL S_DURACAO     : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
  SIGNAL S_CAPTURA     : STD_LOGIC;
  SIGNAL S_CFG_ENTRADA : T_CONFIG;
  SIGNAL S_CFG         : T_CONFIG;
BEGIN

  S_CFG_ENTRADA <= (DUR_VERDE_A   => DUR_VERDE_A,
                    DUR_AMARELO_A => DUR_AMARELO_A,
                    DUR_VERDE_B   => DUR_VERDE_B,
                    DUR_AMARELO_B => DUR_AMARELO_B,
                    N_ROUNDS      => N_ROUNDS);

  -- A CONFIGURACAO E CAPTURADA ENQUANTO A FSM ESTA OCIOSA
  S_CAPTURA <= '1' WHEN S_ESTADO = OCIOSO ELSE '0';

  U_CONFIG : ENTITY WORK.REGISTRADOR_CONFIG
    PORT MAP (
      CLK     => CLK,
      RESET   => RESET,
      CAPTURA => S_CAPTURA,
      ENTRADA => S_CFG_ENTRADA,
      SAIDA   => S_CFG
    );

  U_FSM : ENTITY WORK.FSM_SEMAFORO
    PORT MAP (
      CLK         => CLK,
      RESET       => RESET,
      START       => START,
      N_ROUNDS    => S_CFG.N_ROUNDS,
      TC          => S_TC,
      ESTADO      => S_ESTADO,
      ESTADO_PROX => S_ESTADO_PROX,
      CARREGA     => S_CARREGA,
      BUSY        => S_BUSY,
      DONE        => DONE
    );

  -- A TABELA RECEBE O PROXIMO ESTADO: A DURACAO JA ESTA PRONTA NO
  -- CLOCK EM QUE O TEMPORIZADOR CARREGA
  U_TABELA : ENTITY WORK.TABELA_DURACAO
    PORT MAP (
      CONFIG  => S_CFG,
      ESTADO  => S_ESTADO_PROX,
      DURACAO => S_DURACAO
    );

  U_TEMPORIZADOR : ENTITY WORK.TEMPORIZADOR
    PORT MAP (
      CLK      => CLK,
      RESET    => RESET,
      CARREGA  => S_CARREGA,
      HABILITA => S_BUSY,
      DURACAO  => S_DURACAO,
      TC       => S_TC
    );

  U_DECODIFICADOR : ENTITY WORK.DECODIFICADOR_LUZES
    PORT MAP (
      ESTADO => S_ESTADO,
      LUZ_A  => LUZ_A,
      LUZ_B  => LUZ_B
    );

  BUSY <= S_BUSY;

END ARCHITECTURE RTL;

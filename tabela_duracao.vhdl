LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- TABELA COMBINACIONAL: DADO UM ESTADO, DEVOLVE A DURACAO DELE EM CICLOS.
ENTITY TABELA_DURACAO IS
  GENERIC (
    DUR_VERDE_A   : POSITIVE := 10;
    DUR_AMARELO_A : POSITIVE := 3;
    DUR_VERDE_B   : POSITIVE := 10;
    DUR_AMARELO_B : POSITIVE := 3
  );
  PORT (
    ESTADO  : IN  T_ESTADO;
    DURACAO : OUT UNSIGNED(LARGURA_DUR - 1 DOWNTO 0)
  );
END ENTITY TABELA_DURACAO;

ARCHITECTURE RTL OF TABELA_DURACAO IS
  CONSTANT MAX_DUR : NATURAL := 2**LARGURA_DUR - 1;
BEGIN

  ASSERT DUR_VERDE_A   <= MAX_DUR REPORT "DUR_VERDE_A EXCEDE LARGURA_DUR"   SEVERITY FAILURE;
  ASSERT DUR_AMARELO_A <= MAX_DUR REPORT "DUR_AMARELO_A EXCEDE LARGURA_DUR" SEVERITY FAILURE;
  ASSERT DUR_VERDE_B   <= MAX_DUR REPORT "DUR_VERDE_B EXCEDE LARGURA_DUR"   SEVERITY FAILURE;
  ASSERT DUR_AMARELO_B <= MAX_DUR REPORT "DUR_AMARELO_B EXCEDE LARGURA_DUR" SEVERITY FAILURE;

  WITH ESTADO SELECT
    DURACAO <=
      TO_UNSIGNED(DUR_VERDE_A,   LARGURA_DUR) WHEN VERDE_A,
      TO_UNSIGNED(DUR_AMARELO_A, LARGURA_DUR) WHEN AMARELO_A,
      TO_UNSIGNED(DUR_VERDE_B,   LARGURA_DUR) WHEN VERDE_B,
      TO_UNSIGNED(DUR_AMARELO_B, LARGURA_DUR) WHEN AMARELO_B,
      TO_UNSIGNED(1,             LARGURA_DUR) WHEN OCIOSO | FIM;

END ARCHITECTURE RTL;

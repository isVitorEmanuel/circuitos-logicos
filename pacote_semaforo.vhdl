LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;

PACKAGE PACOTE_SEMAFORO IS
  TYPE T_ESTADO IS (OCIOSO, VERDE_A, AMARELO_A, VERDE_B, AMARELO_B, FIM);

  -- TAMANHO DO CONTADOR DO TIMER E DA DURACAO. 8 BITS => DURACOES DE 1 A 255 CICLOS.
  CONSTANT LARGURA_DUR : NATURAL := 8;

  -- DADOS DE ENTRADA DO ALGORITMO: DURACAO DE CADA ESTADO DE LUZ E NUMERO DE ROUNDS.
  -- VALOR 0 E TRATADO COMO 1 (DURACAO PELO TEMPORIZADOR, N_ROUNDS PELA FSM).
  TYPE T_CONFIG IS RECORD
    DUR_VERDE_A   : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    DUR_AMARELO_A : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    DUR_VERDE_B   : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    DUR_AMARELO_B : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
    N_ROUNDS      : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);
  END RECORD T_CONFIG;

  CONSTANT CONFIG_ZERO : T_CONFIG := (OTHERS => (OTHERS => '0'));

END PACKAGE PACOTE_SEMAFORO;

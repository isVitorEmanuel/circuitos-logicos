LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- REGISTRADOR DE CONFIGURACAO COM BYPASS.
-- CAPTURA = '1' (FSM OCIOSA): A SAIDA ACOMPANHA A ENTRADA (BYPASS) E O REGISTRADOR
--           COPIA A ENTRADA A CADA CLOCK. NO CLOCK EM QUE O START E AMOSTRADO,
--           O VALOR VIVO JA ALIMENTA O PRIMEIRO ESTADO E E GUARDADO.
-- CAPTURA = '0' (EXECUTANDO): A SAIDA E O VALOR GUARDADO; MEXER NAS ENTRADAS
--           NO MEIO DA EXECUCAO NAO TEM EFEITO.
ENTITY REGISTRADOR_CONFIG IS
  PORT (
    CLK     : IN  STD_LOGIC;
    RESET   : IN  STD_LOGIC;
    CAPTURA : IN  STD_LOGIC;
    ENTRADA : IN  T_CONFIG;
    SAIDA   : OUT T_CONFIG
  );
END ENTITY REGISTRADOR_CONFIG;

ARCHITECTURE RTL OF REGISTRADOR_CONFIG IS
  SIGNAL REG : T_CONFIG := CONFIG_ZERO;
BEGIN

  PROCESS (CLK)
  BEGIN
    IF RISING_EDGE(CLK) THEN
      IF RESET = '1' THEN
        REG <= CONFIG_ZERO;
      ELSIF CAPTURA = '1' THEN
        REG <= ENTRADA;
      END IF;
    END IF;
  END PROCESS;

  SAIDA <= ENTRADA WHEN CAPTURA = '1' ELSE REG;

END ARCHITECTURE RTL;

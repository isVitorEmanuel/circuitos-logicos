LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE WORK.PACOTE_SEMAFORO.ALL;

-- UNIDADE DE CONTROLE (FSM DE MOORE; CARREGA E ESTADO_PROX DEPENDEM TAMBEM DA TRANSICAO).
-- A FSM NAO SABE QUANTO DURA CADA ESTADO: ELA SO OLHA O TC DO TEMPORIZADOR.
-- A DURACAO DO PROXIMO ESTADO VEM DA TABELA_DURACAO (VIA ESTADO_PROX) E E
-- CARREGADA NO TEMPORIZADOR NO MESMO CLOCK EM QUE O ESTADO MUDA.
ENTITY FSM_SEMAFORO IS
  PORT (
    CLK         : IN  STD_LOGIC;
    RESET       : IN  STD_LOGIC;   -- SINCRONO, ATIVO EM '1'
    START       : IN  STD_LOGIC;
    N_ROUNDS    : IN  UNSIGNED(LARGURA_DUR - 1 DOWNTO 0);  -- CICLOS COMPLETOS (A + B) POR START; 0 = 1
    TC          : IN  STD_LOGIC;   -- FIM DA CONTAGEM DO ESTADO ATUAL
    ESTADO      : OUT T_ESTADO;
    ESTADO_PROX : OUT T_ESTADO;
    CARREGA     : OUT STD_LOGIC;   -- MANDA O TEMPORIZADOR CARREGAR A DURACAO
    BUSY        : OUT STD_LOGIC;   -- '1' ENQUANTO EXECUTA OS ROUNDS
    DONE        : OUT STD_LOGIC    -- '1' POR 1 CICLO AO TERMINAR
  );
END ENTITY FSM_SEMAFORO;

ARCHITECTURE RTL OF FSM_SEMAFORO IS
  SIGNAL EST    : T_ESTADO := OCIOSO;
  SIGNAL PROX   : T_ESTADO;
  SIGNAL RODADA : UNSIGNED(LARGURA_DUR - 1 DOWNTO 0) := (OTHERS => '0');  -- ROUNDS JA CONCLUIDOS
  SIGNAL ULTIMO : STD_LOGIC;   -- '1' SE O ROUND ATUAL E O ULTIMO
BEGIN

  -- RODADA + 1 NUNCA ESTOURA: RODADA <= N_ROUNDS - 1 <= 254
  ULTIMO <= '1' WHEN RODADA + 1 >= N_ROUNDS ELSE '0';

  -- REGISTRADOR DE ESTADO E CONTADOR DE ROUNDS
  PROCESS (CLK)
  BEGIN
    IF RISING_EDGE(CLK) THEN
      IF RESET = '1' THEN
        EST    <= OCIOSO;
        RODADA <= (OTHERS => '0');
      ELSE
        EST <= PROX;

        -- AO FIM DE UM ROUND (AMARELO_B ACABANDO): CONTA, OU ZERA NO ULTIMO
        IF EST = AMARELO_B AND TC = '1' THEN
          IF ULTIMO = '1' THEN
            RODADA <= (OTHERS => '0');
          ELSE
            RODADA <= RODADA + 1;
          END IF;
        END IF;
      END IF;
    END IF;
  END PROCESS;

  -- LOGICA DE PROXIMO ESTADO (COMBINACIONAL)
  PROCESS (EST, START, TC, ULTIMO)
  BEGIN
    PROX <= EST;

    CASE EST IS
      WHEN OCIOSO =>
        IF START = '1' THEN
          PROX <= VERDE_A;
        END IF;

      WHEN VERDE_A =>
        IF TC = '1' THEN
          PROX <= AMARELO_A;
        END IF;

      WHEN AMARELO_A =>
        IF TC = '1' THEN
          PROX <= VERDE_B;
        END IF;

      WHEN VERDE_B =>
        IF TC = '1' THEN
          PROX <= AMARELO_B;
        END IF;

      WHEN AMARELO_B =>
        IF TC = '1' THEN
          IF ULTIMO = '1' THEN
            PROX <= FIM;       -- ULTIMO ROUND
          ELSE
            PROX <= VERDE_A;   -- MAIS UM ROUND
          END IF;
        END IF;

      WHEN FIM =>
        PROX <= OCIOSO;
    END CASE;
  END PROCESS;

  -- SAIDAS
  ESTADO      <= EST;
  ESTADO_PROX <= PROX;

  -- CARREGA A DURACAO SO AO ENTRAR EM UM DOS 4 ESTADOS DE LUZ
  CARREGA <= '1' WHEN PROX /= EST AND PROX /= OCIOSO AND PROX /= FIM ELSE '0';

  BUSY <= '0' WHEN EST = OCIOSO OR EST = FIM ELSE '1';
  DONE <= '1' WHEN EST = FIM ELSE '0';

END ARCHITECTURE RTL;
